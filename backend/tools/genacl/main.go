// Command genacl writes cmd/openenu/acl_gen.go: for every operation in every
// module's OpenAPI fragment, the permission its handler requires.
//
// The permission is read from the handler itself - the string literal in
// `auth.Require(ctx, "example.manage")` inside the method that implements the
// operation in api.go - so there is exactly one place it is written, and the
// generated map cannot disagree with what the server enforces. The MCP
// catalogue (kernel/mcp) reads the map to decide what an agent is offered;
// `make arch` runs this with -check, so a changed guard and a stale map fail
// the build.
//
// An operation whose handler calls no auth.Require is absent: a public auth
// endpoint, or one behind auth.RequireOperator - neither is for an API key.
//
// Invoked by `go generate ./cmd/openenu` with cmd/openenu as the working
// directory.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/open-enu/kernel/spec"
)

const outName = "acl_gen.go"

func main() {
	check := flag.Bool("check", false, "exit 1 if the committed file is stale instead of rewriting it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genacl:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	modules, err := filepath.Abs(filepath.Join("..", "..", "internal", "module"))
	if err != nil {
		return err
	}
	acl, err := collect(modules)
	if err != nil {
		return err
	}
	src, err := render(acl)
	if err != nil {
		return err
	}
	if check {
		cur, err := os.ReadFile(outName)
		if err != nil || !bytes.Equal(cur, src) {
			return fmt.Errorf("%s is stale - run `go generate ./cmd/openenu` and commit the result", outName)
		}
		return nil
	}
	return os.WriteFile(outName, src, 0o644)
}

// collect maps operationId -> permission across every module that has both
// a fragment and an api.go.
func collect(modules string) (map[string]string, error) {
	dirs, err := os.ReadDir(modules)
	if err != nil {
		return nil, err
	}
	acl := map[string]string{}
	for _, d := range dirs {
		if !d.IsDir() {
			continue
		}
		dir := filepath.Join(modules, d.Name())
		fragment, err := os.ReadFile(filepath.Join(dir, "openapi.json"))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		ops, err := spec.Operations(fragment)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", d.Name(), err)
		}
		guards, err := requires(filepath.Join(dir, "internal", "api.go"))
		if err != nil {
			return nil, err
		}
		for _, op := range ops {
			if perm, ok := guards[methodName(op.ID)]; ok {
				acl[op.ID] = perm
			}
		}
	}
	return acl, nil
}

// methodName is oapi-codegen's: post_example_project_create ->
// PostExampleProjectCreate. The compiler already proves every operation has
// its method, so a miss here is a miss in this function, not in a module.
func methodName(operationID string) string {
	var sb strings.Builder
	for _, part := range strings.FieldsFunc(operationID, func(r rune) bool { return r == '_' || r == '-' || r == '.' }) {
		sb.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return sb.String()
}

// requires maps a handler method's name to the first auth.Require literal in
// its body. A method with none is absent.
func requires(path string) (map[string]string, error) {
	src, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	f, err := parser.ParseFile(token.NewFileSet(), path, src, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || fn.Body == nil || !fn.Name.IsExported() {
			continue
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			if _, done := out[fn.Name.Name]; done {
				return false
			}
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 2 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "Require" {
				return true
			}
			if pkg, ok := sel.X.(*ast.Ident); !ok || pkg.Name != "auth" {
				return true
			}
			if lit, ok := call.Args[1].(*ast.BasicLit); ok && lit.Kind == token.STRING {
				if perm, err := strconv.Unquote(lit.Value); err == nil {
					out[fn.Name.Name] = perm
				}
			}
			return true
		})
	}
	return out, nil
}

func render(acl map[string]string) ([]byte, error) {
	ids := make([]string, 0, len(acl))
	for id := range acl {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genacl; DO NOT EDIT.\n")
	b.WriteString("// GENERATED from the auth.Require literal in each module's internal/api.go - regenerate with `go generate ./cmd/openenu`.\n")
	b.WriteString("package main\n\n")
	b.WriteString("// operationPermissions is the ACL the MCP catalogue reads: operationId ->\n")
	b.WriteString("// the permission the handler requires. Public and operator-realm operations\n")
	b.WriteString("// are absent, and so are offered to no API key.\n")
	b.WriteString("var operationPermissions = map[string]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: %q,\n", id, acl[id])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
