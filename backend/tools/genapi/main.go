// Command genapi generates one module's strict server from its openapi.json.
//
// It merges the kernel's shared components into the module's fragment (so
// `$ref: '#/components/schemas/Error'` resolves), writes the result to a
// temporary file and runs oapi-codegen - the pinned `go tool` - producing
// internal/api.gen.go: the models and a StrictServerInterface covering this
// module's operations only. internal/api.go implements it; a handler that
// disagrees with the spec does not compile.
//
// Run by `go generate` from the module directory (the directive lives in
// module.go). -check regenerates into a temp file and diffs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"

	"github.com/open-enu/app/tools/internal/spec"
	"github.com/open-enu/kernel/httpx"
)

const (
	fragment = "openapi.json"
	output   = "internal/api.gen.go"
	config   = `package: internal
generate:
  models: true
  std-http-server: true
  strict-server: true
output-options:
  skip-prune: true
`
)

func main() {
	check := flag.Bool("check", false, "exit 1 if internal/api.gen.go is stale instead of rewriting it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genapi:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	dir, err := os.Getwd()
	if err != nil {
		return err
	}
	name := filepath.Base(dir)
	data, err := os.ReadFile(fragment)
	if err != nil {
		return fmt.Errorf("%s has no %s - every module with routes owns its spec fragment", name, fragment)
	}
	frag, err := spec.ParseFragment(name+"/"+fragment, data)
	if err != nil {
		return err
	}
	shared, err := spec.ParseComponents(httpx.SharedComponents)
	if err != nil {
		return err
	}
	merged, err := spec.Merge("0", shared, map[string]*spec.Document{name: frag})
	if err != nil {
		return err
	}
	input, err := spec.Render(merged)
	if err != nil {
		return err
	}

	tmp, err := os.MkdirTemp("", "genapi-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	specPath := filepath.Join(tmp, "openapi.json")
	cfgPath := filepath.Join(tmp, "config.yaml")
	outPath := filepath.Join(tmp, "api.gen.go")
	if err := os.WriteFile(specPath, input, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(cfgPath, []byte(config+"output: "+outPath+"\n"), 0o644); err != nil {
		return err
	}

	// `go tool` resolves the pinned oapi-codegen from go.mod; cwd stays in the
	// module so the right go.mod is found.
	cmd := exec.Command("go", "tool", "oapi-codegen", "-config", cfgPath, specPath)
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("oapi-codegen failed for %s: %w", name, err)
	}
	gen, err := os.ReadFile(outPath)
	if err != nil {
		return err
	}
	header := []byte("// Code generated by oapi-codegen via tools/genapi; DO NOT EDIT.\n// GENERATED from openapi.json - regenerate with `go generate` in this module.\n\n")
	gen = append(header, gen...)

	if check {
		cur, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(cur, gen) {
			return fmt.Errorf("%s/%s is stale - run `go generate ./internal/module/%s` and commit the result", name, output, name)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		return err
	}
	return os.WriteFile(output, gen, 0o644)
}
