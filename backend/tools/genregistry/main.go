// Command genregistry writes cmd/openenu/module_registry_gen.go from the
// module.yaml files under internal/module/.
//
// This is the whole of "no central file edited by hand": a directory with a
// manifest and a `var Module` becomes an import and an entry in the list the
// kernel registry is built from. `make arch` runs it with -check, so a module
// present on disk and absent from the committed file fails the build instead
// of silently serving nothing.
//
// Invoked by `go generate ./cmd/openenu` (the directive is in main.go), with
// cmd/openenu as the working directory.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/open-enu/kernel/module"
)

const outName = "module_registry_gen.go"

func main() {
	check := flag.Bool("check", false, "exit 1 if the committed file is stale instead of rewriting it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "genregistry:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	backend, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		return err
	}
	modPath, err := modulePath(filepath.Join(backend, "go.mod"))
	if err != nil {
		return err
	}
	names, err := discover(filepath.Join(backend, "internal", "module"))
	if err != nil {
		return err
	}
	src, err := render(modPath, names)
	if err != nil {
		return err
	}
	if check {
		cur, err := os.ReadFile(outName)
		if err != nil || !bytes.Equal(cur, src) {
			return fmt.Errorf("%s is stale - run `go generate ./cmd/openenu` and commit the result", outName)
		}
		return nil
	}
	return os.WriteFile(outName, src, 0o644)
}

var modLine = regexp.MustCompile(`(?m)^module\s+(\S+)`)

func modulePath(gomod string) (string, error) {
	data, err := os.ReadFile(gomod)
	if err != nil {
		return "", err
	}
	m := modLine.FindSubmatch(data)
	if m == nil {
		return "", fmt.Errorf("%s: no module line", gomod)
	}
	return string(m[1]), nil
}

var hasModuleVar = regexp.MustCompile(`(?m)^var Module\b`)

// discover returns the manifest names, sorted, after checking each module is
// importable as the registry expects: a package named like the directory
// that exports `var Module`.
func discover(root string) ([]string, error) {
	entries, err := os.ReadDir(root)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		dir := filepath.Join(root, e.Name())
		if _, err := os.Stat(filepath.Join(dir, "module.yaml")); err != nil {
			continue // a directory without a manifest is not a module - and not an error
		}
		m, err := module.ReadManifest(dir)
		if err != nil {
			return nil, err
		}
		src, err := os.ReadFile(filepath.Join(dir, "module.go"))
		if err != nil {
			return nil, fmt.Errorf("%s has a module.yaml but no module.go - `make module NAME=%s` writes the right one", dir, m.Name)
		}
		if !hasModuleVar.Match(src) {
			return nil, fmt.Errorf("%s/module.go must declare `var Module = module.Module{...}` - it is the only thing the registry reads", dir)
		}
		if !bytes.Contains(src, []byte("package "+m.Name+"\n")) {
			return nil, fmt.Errorf("%s/module.go must be `package %s` - the package is the module name", dir, m.Name)
		}
		names = append(names, m.Name)
	}
	sort.Strings(names)
	return names, nil
}

func render(modPath string, names []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/genregistry; DO NOT EDIT.\n")
	b.WriteString("// GENERATED from internal/module/*/module.yaml - regenerate with `go generate ./cmd/openenu`.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import (\n\t\"github.com/open-enu/kernel/module\"\n")
	if len(names) > 0 {
		b.WriteString("\n")
		for _, n := range names {
			fmt.Fprintf(&b, "\t%s \"%s/internal/module/%s\"\n", n, modPath, n)
		}
	}
	b.WriteString(")\n\n")
	b.WriteString("// discoveredModules is every directory under internal/module with a\n// module.yaml, in name order. The registry decides what is enabled.\n")
	b.WriteString("var discoveredModules = []module.Module{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%s.Module,\n", n)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
