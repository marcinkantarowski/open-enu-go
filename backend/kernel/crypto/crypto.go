// Package crypto is field encryption: AES-256-GCM under a key derived per
// tenant from one master secret.
//
// The wire format (`v1:iv:ciphertext:tag`, each part base64) and the
// derivation (HKDF-SHA256 of the master, salted with the tenant id, under a
// fixed info string) are a contract with every row already written.
// crypto_test.go pins both to a fixed test vector; a change that breaks it
// makes every stored row unreadable, which is the one thing this package
// must never do.
//
// A module's repository encrypts a column on write and decrypts it on read
// through the Encryptor on platform.Services (example/internal/repository.go
// shows the pair). What a module may also call is Encryptor.HashForLookup,
// to fill the sibling *_hash column that equality lookups go through - an
// encrypted value differs on every write and cannot be queried. The lookup
// hash is keyed (HMAC under a sub-key of the same master), so a copy of the
// database alone does not turn a hash column back into addresses.
package crypto

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/hkdf"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
	"sync"
)

const (
	version  = "v1"
	ivBytes  = 12
	tagBytes = 16
	keyBytes = 32
	// hkdfInfo is the derivation context; changing it rotates every key.
	hkdfInfo = "open-enu:field:v1"
	// lookupInfo derives the lookup-hash key; changing it orphans every
	// *_hash column.
	lookupInfo = "open-enu:lookup:v1"
	// MinMasterKeyLen is what `make env` generates; a shorter key was set by hand.
	MinMasterKeyLen = 32
)

// ErrNotEncrypted is returned for a payload without the v1 prefix. A plaintext
// value in an encrypted column usually means the column was added before the
// declaration - backfill it.
var ErrNotEncrypted = errors.New("crypto: not a recognised encrypted payload")

// ErrDecrypt is returned when the key is wrong, the tenant is wrong, or the
// ciphertext was tampered with. GCM cannot tell which, which is the point.
var ErrDecrypt = errors.New("crypto: decryption failed - the master key changed, or this row belongs to a different tenant than the current scope")

// KeyProvider supplies the data-encryption key for a tenant. An interface
// from day one so a KMS later is one type, not a refactor of every encrypted
// column. tenantID "" is the global key.
type KeyProvider interface {
	KeyFor(tenantID string) ([]byte, error)
}

// DerivedKeys derives per-tenant keys from one master secret by HKDF-SHA256.
// No key material is stored per tenant - the key is a pure function of the
// master and the tenant id - so there is no key table to back up and no
// bootstrap when a tenant is created. Rotating one tenant's salt is
// cryptographic erasure. The trade is that the master is catastrophic to lose.
type DerivedKeys struct {
	master []byte
	mu     sync.Mutex
	cache  map[string][]byte
}

// NewDerivedKeys refuses a master shorter than MinMasterKeyLen.
func NewDerivedKeys(master string) (*DerivedKeys, error) {
	if len(master) < MinMasterKeyLen {
		return nil, fmt.Errorf("crypto: APP_ENCRYPTION_KEY must be at least %d characters; it is generated by `make env` - a short one was set by hand", MinMasterKeyLen)
	}
	return &DerivedKeys{master: []byte(master), cache: map[string][]byte{}}, nil
}

// KeyFor derives (and caches, per process) the key for a tenant.
func (d *DerivedKeys) KeyFor(tenantID string) ([]byte, error) {
	salt := tenantID
	if salt == "" {
		salt = "global"
	}
	d.mu.Lock()
	defer d.mu.Unlock()
	if k, ok := d.cache[salt]; ok {
		return k, nil
	}
	k, err := hkdf.Key(sha256.New, d.master, []byte(salt), hkdfInfo, keyBytes)
	if err != nil {
		return nil, fmt.Errorf("crypto: derive key: %w", err)
	}
	d.cache[salt] = k
	return k, nil
}

// LookupKeyProvider is a KeyProvider that also supplies the key the lookup
// hash is keyed with. DerivedKeys is one; a provider that is not gets its
// lookup key derived from its global key.
type LookupKeyProvider interface {
	LookupKey() ([]byte, error)
}

// LookupKey is HKDF-SHA256 of the master under its own info string: a
// sub-key, never the field key, so a leaked lookup key decrypts nothing.
func (d *DerivedKeys) LookupKey() ([]byte, error) {
	return DeriveKey(d.master, lookupInfo), nil
}

// DeriveKey derives a 32-byte sub-key of secret for one purpose, named by
// info (HKDF-SHA256, no salt). Two consumers of one secret - the token
// signer and the download-URL signer under APP_SECRET - each get their own,
// so a signature made for one is never valid for the other.
func DeriveKey(secret []byte, info string) []byte {
	k, err := hkdf.Key(sha256.New, secret, nil, info, keyBytes)
	if err != nil { // only for an output longer than HKDF allows
		panic(fmt.Sprintf("crypto: derive %s: %v", info, err))
	}
	return k
}

// Encryptor encrypts and decrypts field values and computes the lookup
// hash. Safe for concurrent use.
type Encryptor struct {
	keys   KeyProvider
	lookup []byte
}

// NewEncryptor wraps a key provider. It panics when the provider cannot
// give a lookup key, which happens at boot or not at all.
func NewEncryptor(keys KeyProvider) *Encryptor {
	var lookup []byte
	var err error
	if l, ok := keys.(LookupKeyProvider); ok {
		lookup, err = l.LookupKey()
	} else {
		var global []byte
		if global, err = keys.KeyFor(""); err == nil {
			lookup = DeriveKey(global, lookupInfo)
		}
	}
	if err != nil {
		panic(fmt.Sprintf("crypto: lookup key: %v", err))
	}
	return &Encryptor{keys: keys, lookup: lookup}
}

// Encrypt returns `v1:iv:ciphertext:tag`, each part base64, under the
// tenant's key. The IV is random, so the same plaintext never produces the
// same payload twice.
func (e *Encryptor) Encrypt(plaintext, tenantID string) (string, error) {
	gcm, err := e.aead(tenantID)
	if err != nil {
		return "", err
	}
	iv := make([]byte, ivBytes)
	if _, err := rand.Read(iv); err != nil {
		return "", fmt.Errorf("crypto: iv: %w", err)
	}
	sealed := gcm.Seal(nil, iv, []byte(plaintext), nil)
	ct, tag := sealed[:len(sealed)-tagBytes], sealed[len(sealed)-tagBytes:]
	enc := base64.StdEncoding.EncodeToString
	return strings.Join([]string{version, enc(iv), enc(ct), enc(tag)}, ":"), nil
}

// Decrypt reverses Encrypt. A payload without the version prefix is
// ErrNotEncrypted; anything that fails authentication is ErrDecrypt.
func (e *Encryptor) Decrypt(payload, tenantID string) (string, error) {
	parts := strings.SplitN(payload, ":", 4)
	if len(parts) != 4 || parts[0] != version {
		return "", ErrNotEncrypted
	}
	dec := func(s string) []byte {
		b, err := base64.StdEncoding.DecodeString(s)
		if err != nil {
			return nil
		}
		return b
	}
	iv, ct, tag := dec(parts[1]), dec(parts[2]), dec(parts[3])
	if len(iv) != ivBytes || len(tag) != tagBytes {
		return "", ErrDecrypt
	}
	gcm, err := e.aead(tenantID)
	if err != nil {
		return "", err
	}
	plain, err := gcm.Open(nil, iv, append(append([]byte{}, ct...), tag...), nil)
	if err != nil {
		return "", ErrDecrypt
	}
	return string(plain), nil
}

func (e *Encryptor) aead(tenantID string) (cipher.AEAD, error) {
	key, err := e.keys.KeyFor(tenantID)
	if err != nil {
		return nil, err
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("crypto: cipher: %w", err)
	}
	return cipher.NewGCMWithTagSize(block, tagBytes)
}

// HashForLookup is the deterministic hash for equality lookups on an
// encrypted column: HMAC-SHA256, hex, under the lookup sub-key of the master
// key, of the value trimmed (spaces, tabs, line breaks, NUL and vertical tab)
// and lower-cased, so the same address typed with different case or
// surrounding whitespace hashes the same. Keyed, so a database dump without
// APP_ENCRYPTION_KEY cannot be reversed by hashing a list of guesses.
// Equality only - it leaks nothing beyond "these two rows hold the same
// value", which is exactly what an index needs.
func (e *Encryptor) HashForLookup(value string) string {
	m := hmac.New(sha256.New, e.lookup)
	m.Write([]byte(strings.ToLower(strings.Trim(value, " \t\n\r\x00\x0b"))))
	return hex.EncodeToString(m.Sum(nil))
}
